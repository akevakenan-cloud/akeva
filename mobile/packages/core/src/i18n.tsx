const dictionaries: Record<Lang, Record<Key, string>> = { fr, en };
export type T = (key: Key | string, vars?: Record<string, string | number>) => string;

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: T } | null>(null);
const STORAGE_KEY = "akeva.lang";

function deviceLang(): Lang {
  return getLocales()[0]?.languageCode === "en" ? "en" : "fr"; // French is the default in the region
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(deviceLang);

  useEffect(() => {
    AsyncStorage.getItem(STORAGE_KEY).then((v) => (v === "fr" || v === "en") && setLangState(v)).catch(() => {});
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    AsyncStorage.setItem(STORAGE_KEY, l).catch(() => {});
  }, []);

  const t: T = useCallback(
    (key, vars) => {
      let s = (dictionaries[lang] as Record<string, string>)[key] ?? (fr as Record<string, string>)[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
      return s;
    },
    [lang],
  );

  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const c = useContext(Ctx);
  if (!c) throw new Error("useI18n outside I18nProvider");
  return c;
}
